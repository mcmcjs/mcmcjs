#!/usr/bin/env node
// Regenerates packages/cli/src/templates.generated.ts from packages/cli/templates.
// The files are embedded rather than read from disk so a single-file binary can
// seed a project too. Run via `pnpm gen:templates`; a test keeps the two in sync.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "packages", "cli", "templates");
const out = join(root, "packages", "cli", "src", "templates.generated.ts");

const names = readdirSync(dir).sort();
const entries = names
  .map(
    (name) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(dir, name), "utf8"))},`,
  )
  .join("\n");

writeFileSync(
  out,
  `// Generated by scripts/gen-templates.mjs from packages/cli/templates. Do not edit.
/** The example project files, embedded so a compiled binary ships them too. */
export const TEMPLATE_FILES: Record<string, string> = {
${entries}
};
`,
);
process.stdout.write(`wrote ${out} (${names.length} files)\n`);
