#!/usr/bin/env node
// Regenerates packages/julia/src/assets.generated.ts from the Julia driver and
// the pinned environment. Embedding them (rather than shipping loose files next
// to the bundle) lets a single-file binary carry the driver too; at runtime they
// are written to a cache directory that Julia reads with @__DIR__ intact.
// Run via `pnpm gen:julia-assets`; a test keeps the two in sync.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages", "julia", "src");
const out = join(src, "assets.generated.ts");

/** Relative names, kept flat so `include(joinpath(@__DIR__, ...))` resolves. */
export const ASSETS = [
  ["driver.jl", join(src, "driver", "driver.jl")],
  ["worker.jl", join(src, "driver", "worker.jl")],
  ["fitlib.jl", join(src, "driver", "fitlib.jl")],
  ["julia-env/Project.toml", join(src, "julia-env", "Project.toml")],
  ["julia-env/Manifest.toml", join(src, "julia-env", "Manifest.toml")],
];

const entries = ASSETS.map(
  ([name, path]) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(path, "utf8"))},`,
).join("\n");

writeFileSync(
  out,
  `// Generated by scripts/gen-julia-assets.mjs. Do not edit; edit the sources it reads.
/** The Julia driver and pinned environment, embedded so a binary ships them. */
export const JULIA_ASSETS: Record<string, string> = {
${entries}
};
`,
);
process.stdout.write(`wrote ${out} (${ASSETS.length} files)\n`);
